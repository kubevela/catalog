#!/usr/bin/env bash
# Generates each addon's opt-in definitions.
#
# Every definition in addons/<addon>/optional/<parameter>/ is rendered into
# addons/<addon>/resources/optional-<parameter>.cue, applied only when the boolean
# parameter <parameter> is true. The addon loader applies all of definitions/, so
# this is how an addon ships a definition the user must ask for, such as a global
# policy. The addon declares the parameter in its parameter.cue.
#
#   hack/addon-optional/sync.sh            generate for every addon
#   hack/addon-optional/sync.sh --check    change nothing; exit 1 if any addon is out of step
#   hack/addon-optional/sync.sh -v         also name the addons already in step
#
# Needs vela (VELA=<path> to pick one) and python3 with PyYAML.
# Exit codes: 0 in step (or generated), 1 out of step under --check, 2 usage, a missing tool or a broken addon.
set -euo pipefail

check=0
verbose=0
for arg in "$@"; do
	case "$arg" in
	--check) check=1 ;;
	-v) verbose=1 ;;
	-h | --help)
		sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'
		exit 0
		;;
	*)
		echo "unknown argument: $arg" >&2
		exit 2
		;;
	esac
done

vela=${VELA:-vela}
if ! command -v "$vela" >/dev/null 2>&1; then
	echo "vela not found: put it on PATH or set VELA=<path>" >&2
	exit 2
fi
if ! python3 -c 'import yaml' 2>/dev/null; then
	echo "python3 cannot import yaml: pip install pyyaml" >&2
	exit 2
fi

root=$(cd "$(dirname "$0")/../.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

generated=0
stale=0
same=0
broken=0

# to_cue reads rendered definition YAML on stdin and writes the guarded resources file.
to_cue() {
	python3 -c '
import json, sys, yaml
param, src = sys.argv[1], sys.argv[2]
out = ["// Generated by hack/addon-optional/sync.sh from %s: edit that, then run the script." % src,
       "package main", "", "if parameter.%s {" % param]
for doc in yaml.safe_load_all(sys.stdin):
    if not doc:
        continue
    doc["metadata"]["namespace"] = "vela-system"
    body = json.dumps(doc, indent="\t", sort_keys=True).replace("\n", "\n\t")
    out.append("\toutputs: %s: %s" % (json.dumps("optional-" + doc["metadata"]["name"]), body))
out.append("}")
print("\n".join(out))
' "$1" "$2"
}

for dir in "$root"/addons/*/ "$root"/experimental/addons/*/; do
	addon=${dir%/}
	name=${addon#"$root"/}

	# Drop generated files whose source folder is gone.
	for res in "$addon"/resources/optional-*.cue; do
		[ -f "$res" ] || continue
		param=${res##*/optional-}
		param=${param%.cue}
		[ -d "$addon/optional/$param" ] && continue
		if [ "$check" = 1 ]; then
			echo "STALE  $name: resources/optional-$param.cue has no optional/$param/"
			stale=$((stale + 1))
		else
			rm "$res"
			echo "removed $name: resources/optional-$param.cue"
			generated=$((generated + 1))
		fi
	done

	[ -d "$addon/optional" ] || continue
	for opt in "$addon"/optional/*/; do
		opt=${opt%/}
		param=${opt##*/}
		out="$addon/resources/optional-$param.cue"
		if ! grep -q "^[[:space:]]*$param:" "$addon/parameter.cue"; then
			echo "BROKEN $name: parameter.cue does not declare $param" >&2
			broken=$((broken + 1))
			continue
		fi
		mkdir -p "$tmp/rendered"
		if ! "$vela" def render "$opt" -o "$tmp/rendered" >"$tmp/render.log" 2>&1; then
			echo "BROKEN $name: vela def render optional/$param failed:" >&2
			cat "$tmp/render.log" >&2
			broken=$((broken + 1))
			rm -rf "$tmp/rendered"
			continue
		fi
		# One document per file; the separator keeps them apart.
		for f in "$tmp/rendered"/*.yaml; do
			echo ---
			cat "$f"
		done | to_cue "$param" "optional/$param/" >"$tmp/out.cue"
		rm -rf "$tmp/rendered"

		if cmp -s "$tmp/out.cue" "$out"; then
			same=$((same + 1))
			[ "$verbose" = 1 ] && echo "ok     $name: optional/$param"
			continue
		fi
		if [ "$check" = 1 ]; then
			echo "STALE  $name: resources/optional-$param.cue"
			stale=$((stale + 1))
		else
			mkdir -p "$addon/resources"
			cp "$tmp/out.cue" "$out"
			echo "generated $name: resources/optional-$param.cue"
			generated=$((generated + 1))
		fi
	done
done

echo "addon-optional: $generated generated, $stale stale, $same in step, $broken broken"
[ "$broken" = 0 ] || exit 2
[ "$stale" = 0 ] || exit 1
