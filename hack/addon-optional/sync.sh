#!/usr/bin/env bash
# Generates each addon's conditional definitions.
#
# The addon loader applies all of definitions/, so a definition that depends on a
# parameter lives elsewhere and is rendered into resources/, guarded by it:
#
#   <addon>/optional/<param>/*.cue          -> resources/optional-<param>.cue, applied when the bool <param> is true
#   <addon>/variants/<param>/<value>/*.cue  -> resources/variant-<param>.cue, each <value>'s applied when <param>, as text, is <value>
#
# A definition stays a definition there, so vela def test runs against it. The addon
# declares <param> in its parameter.cue.
#
#   hack/addon-optional/sync.sh            generate for every addon
#   hack/addon-optional/sync.sh --check    change nothing; exit 1 if any addon is out of step
#   hack/addon-optional/sync.sh -v         also name the files already in step
#
# Needs vela (VELA=<path> to pick one) and python3 with PyYAML.
# Exit codes: 0 in step (or generated), 1 out of step under --check, 2 usage, a missing tool or a broken addon.
set -euo pipefail

check=0
verbose=0
for arg in "$@"; do
	case "$arg" in
	--check) check=1 ;;
	-v) verbose=1 ;;
	-h | --help)
		sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'
		exit 0
		;;
	*)
		echo "unknown argument: $arg" >&2
		exit 2
		;;
	esac
done

vela=${VELA:-vela}
if ! command -v "$vela" >/dev/null 2>&1; then
	echo "vela not found: put it on PATH or set VELA=<path>" >&2
	exit 2
fi
if ! python3 -c 'import yaml' 2>/dev/null; then
	echo "python3 cannot import yaml: pip install pyyaml" >&2
	exit 2
fi

root=$(cd "$(dirname "$0")/../.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

generated=0
stale=0
same=0
broken=0

# block <guard> <src> appends one guarded block of the definitions rendered into $tmp/rendered to $tmp/out.cue.
block() {
	python3 -c '
import json, sys, yaml
guard, src = sys.argv[1], sys.argv[2]
out = ["", "// From %s" % src, "if %s {" % guard]
docs = [d for f in sorted(sys.argv[3:]) for d in yaml.safe_load_all(open(f))]
for doc in docs:
    if not doc:
        continue
    doc["metadata"]["namespace"] = "vela-system"
    body = json.dumps(doc, indent="\t", sort_keys=True).replace("\n", "\n\t")
    out.append("\toutputs: %s: %s" % (json.dumps("addon-def-" + doc["metadata"]["name"]), body))
out.append("}")
print("\n".join(out))
' "$1" "$2" "$tmp/rendered"/*.yaml >>"$tmp/out.cue"
}

# render <dir> renders every definition in <dir> into $tmp/rendered, or reports why not.
render() {
	rm -rf "$tmp/rendered"
	mkdir -p "$tmp/rendered"
	if ! "$vela" def render "$1" -o "$tmp/rendered" >"$tmp/render.log" 2>&1; then
		echo "BROKEN $name: vela def render ${1#"$addon"/} failed:" >&2
		cat "$tmp/render.log" >&2
		return 1
	fi
}

# emit <out> compares $tmp/out.cue with <out>, then writes or reports it.
emit() {
	if cmp -s "$tmp/out.cue" "$1"; then
		same=$((same + 1))
		[ "$verbose" = 1 ] && echo "ok     $name: ${1#"$addon"/}"
		return 0
	fi
	if [ "$check" = 1 ]; then
		echo "STALE  $name: ${1#"$addon"/}"
		stale=$((stale + 1))
	else
		mkdir -p "$(dirname "$1")"
		cp "$tmp/out.cue" "$1"
		echo "generated $name: ${1#"$addon"/}"
		generated=$((generated + 1))
	fi
}

declared() {
	grep -q "^[[:space:]]*$1:" "$addon/parameter.cue" && return 0
	echo "BROKEN $name: parameter.cue does not declare $1" >&2
	return 1
}

header() {
	printf '// Generated by hack/addon-optional/sync.sh from %s: edit that, then run the script.\npackage main\n' "$1" >"$tmp/out.cue"
}

for dir in "$root"/addons/*/ "$root"/experimental/addons/*/; do
	addon=${dir%/}
	name=${addon#"$root"/}

	# Drop generated files whose source folder is gone.
	for res in "$addon"/resources/optional-*.cue "$addon"/resources/variant-*.cue; do
		[ -f "$res" ] || continue
		kind=${res##*/}
		kind=${kind%%-*}
		param=${res##*/"$kind"-}
		param=${param%.cue}
		src=optional
		[ "$kind" = variant ] && src=variants
		[ -d "$addon/$src/$param" ] && continue
		if [ "$check" = 1 ]; then
			echo "STALE  $name: ${res#"$addon"/} has no $src/$param/"
			stale=$((stale + 1))
		else
			rm "$res"
			echo "removed $name: ${res#"$addon"/}"
			generated=$((generated + 1))
		fi
	done

	for opt in "$addon"/optional/*/; do
		[ -d "$opt" ] || continue
		opt=${opt%/}
		param=${opt##*/}
		declared "$param" || { broken=$((broken + 1)); continue; }
		render "$opt" || { broken=$((broken + 1)); continue; }
		header "optional/$param/"
		block "parameter.$param" "optional/$param/"
		emit "$addon/resources/optional-$param.cue"
	done

	for var in "$addon"/variants/*/; do
		[ -d "$var" ] || continue
		var=${var%/}
		param=${var##*/}
		declared "$param" || { broken=$((broken + 1)); continue; }
		header "variants/$param/"
		ok=1
		for val in "$var"/*/; do
			[ -d "$val" ] || continue
			val=${val%/}
			value=${val##*/}
			render "$val" || { ok=0; break; }
			block "\"\\(parameter.$param)\" == \"$value\"" "variants/$param/$value/"
		done
		[ "$ok" = 1 ] || { broken=$((broken + 1)); continue; }
		emit "$addon/resources/variant-$param.cue"
	done
done

echo "addon-optional: $generated generated, $stale stale, $same in step, $broken broken"
[ "$broken" = 0 ] || exit 2
[ "$stale" = 0 ] || exit 1
